"""Rebuild the schematic centreline used by the flat Bahrain prototype.
Input: Honda official base.svg, path.st0. Output: derived uniformly sampled
geometric control points, not the source artwork. Scale normalized to 5412m.
"""
import re,json,math,sys
from pathlib import Path
import numpy as np
from scipy.ndimage import gaussian_filter1d
import matplotlib;matplotlib.use('Agg')
import matplotlib.pyplot as plt
root=Path(__file__).resolve().parents[1]
svg=Path(sys.argv[1]).read_text()
d=re.search(r'<path class="st0" d="([^"]+)"',svg).group(1)
a=re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?',d)
i=0;cmd=None;p=np.zeros(2);prev=None;pts=[]
while i<len(a):
 if a[i].isalpha():cmd=a[i];i+=1
 if cmd in 'zZ':break
 if cmd in 'mM':
  p=np.array(list(map(float,a[i:i+2])));i+=2;pts.append(p.copy());prev=None;continue
 n=6 if cmd in 'cC' else 4
 q=np.array(list(map(float,a[i:i+n]))).reshape(-1,2);i+=n
 if cmd.islower():q=q+p
 if cmd in 'sS':q=np.array([2*p-prev,*q])
 b,c,end=q
 for t in np.linspace(0,1,161)[1:]:pts.append((1-t)**3*p+3*(1-t)**2*t*b+3*(1-t)*t*t*c+t**3*end)
 prev=c;p=end
pts=np.array(pts);ds=np.r_[0,np.cumsum(np.linalg.norm(np.diff(pts,axis=0),axis=1))];scale=5412/ds[-1]
# Uniform 8m controls, preserving periodic closure; B-spline adds small smoothing.
ss=np.linspace(0,ds[-1],round(5412/8),endpoint=False);xy=np.array([np.interp(ss,ds,pts[:,j]) for j in range(2)]).T
idx=np.argmin(np.linalg.norm(xy-[465,403.6],axis=1));xy=np.roll(xy,-idx,axis=0)
# Origin at start/finish, mathematical y points north; SVG order is racing direction.
origin=xy[0].copy();world=(xy-origin)*[scale,-scale]
world=gaussian_filter1d(world,3,axis=0,mode="wrap")
(root/'racing/src/bahrain-layout.js').write_text('// Bahrain GP flat schematic trace; official Honda circuit guide + F1 5.412km.\n// Generated by tools/trace-bahrain.py; world metres, racing direction.\nexport const BAHRAIN_CONTROL='+json.dumps(np.round(world,4).tolist(),separators=(',',':'))+';\n')
fig,ax=plt.subplots(figsize=(10,7));ax.plot(world[:,0],world[:,1],lw=3,color='#183b48');ax.scatter(*world[0],c='red');
for j in range(0,len(world),30):ax.text(*world[j],str(j),fontsize=8)
ax.axis('equal');ax.grid();fig.savefig('/workspace/scratch/a92954a28b6a/bahrain-outline.png',dpi=140)
print({'controls':len(world),'rawScale':scale,'sourcePixelLength':ds[-1]})
